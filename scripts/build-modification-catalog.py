"""Record every modification STL with the original filename and relative path."""
import json
import os
from pathlib import Path

root = Path(__file__).resolve().parent.parent
configured = os.environ.get('VAULT_RESOURCE_ROOT')
candidates = [Path(configured).expanduser().resolve()] if configured else [root, root.parent]
resource_root = next((candidate for candidate in candidates if (candidate / '03. MODIFICATIONS').is_dir()), None)
if resource_root is None:
    raise SystemExit('Modification resources not found. Set VAULT_RESOURCE_ROOT to the Vault resource folder.')
paths = sorted(path.relative_to(resource_root).as_posix() for path in (resource_root / '03. MODIFICATIONS').rglob('*') if path.is_file() and path.suffix.lower() == '.stl')
if not paths:
    raise SystemExit('No modification STL files found; existing catalog was not changed.')
(root / 'assets/modification-files.js').write_text(
    '/* Generated by scripts/build-modification-catalog.py. */\n'
    'globalThis.ModificationFiles = ' + json.dumps(paths, ensure_ascii=False, indent=2) + ';\n',
    encoding='utf-8'
)
print(f'Recorded {len(paths)} modification STL paths.')
